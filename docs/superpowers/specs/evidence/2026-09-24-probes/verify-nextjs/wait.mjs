// NODE_OPTIONS=--inspect-wait with next dev: who waits, where does next-server's inspector go?
import { spawn, execFileSync } from "node:child_process";
import path from "node:path";
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const [, , appArg, flag, port, http] = process.argv;
const app = path.resolve(appArg);
const env = { ...process.env, NEXT_TELEMETRY_DISABLED: "1", FORCE_COLOR: "0", NODE_OPTIONS: `--${flag}=127.0.0.1:${port}` };
const child = spawn(process.execPath, [path.join(app, "node_modules/next/dist/bin/next"), "dev", "-p", http], { cwd: app, env, detached: true, stdio: ["ignore", "pipe", "pipe"] });
let out = ""; child.stdout.on("data", (d) => (out += d)); child.stderr.on("data", (d) => (out += d));
const kill = () => { try { process.kill(-child.pid, "SIGKILL"); } catch {} };
process.on("exit", kill);
const ports = () => { try { return execFileSync("lsof", ["-a", "-g", String(child.pid), "-iTCP", "-sTCP:LISTEN", "-P", "-n", "-Fpn"], { encoding: "utf8" }).replace(/\n/g, " "); } catch (e) { return String(e.stdout ?? "").replace(/\n/g, " "); } };
await sleep(3000);
const R = { before: { ready: /Ready in/.test(out), ports: ports() } };
const list = await (await fetch(`http://127.0.0.1:${port}/json/list`)).json();
const ws = new WebSocket(list[0].webSocketDebuggerUrl);
await new Promise((r) => (ws.onopen = r));
let id = 0; const pend = new Map();
ws.onmessage = (e) => { const m = JSON.parse(e.data); if (m.id) { pend.get(m.id)?.(m); pend.delete(m.id); } };
const send = (method, params = {}) => new Promise((r) => { const i = ++id; pend.set(i, r); ws.send(JSON.stringify({ id: i, method, params })); });
R.pidAtWait = (await send("Runtime.evaluate", { expression: "process.pid", returnByValue: true })).result?.result?.value ?? null;
R.titleAtWait = (await send("Runtime.evaluate", { expression: "process.title", returnByValue: true })).result?.result?.value ?? null;
await send("Runtime.enable");
await send("Runtime.runIfWaitingForDebugger");
await sleep(6000);
R.after = { ready: /Ready in/.test(out), ports: ports() };
R.tail = out.split("\n").filter(Boolean).map((l) => l.replace(/[0-9a-f-]{36}/, "<uuid>")).slice(-12);
ws.close();
console.log(JSON.stringify(R, null, 1));
kill();
setTimeout(() => process.exit(0), 300);
